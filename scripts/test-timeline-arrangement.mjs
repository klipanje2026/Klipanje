import assert from 'node:assert/strict';
import {loadTestModule} from './test-ts-module.mjs';
const {moveTimelineClip,repairOverlayOverlaps,editOverlayTiming,rippleOverlays}=await loadTestModule('lib/timeline-arrangement.ts','work/timeline-arrangement-tests');
const {separateSceneOverlaps}=await loadTestModule('lib/scene-ripple.ts','work/timeline-arrangement-tests');
const c=(id,start,len,props={})=>({id,type:'video',layer:1,start,inPoint:0,outPoint:len,...props});
const rows=[c('first',0,4,{linksDetached:true}),c('second',4,3,{groupId:'b',segmentIds:['b']}),c('third',7,3),c('voice',4,3,{type:'audio',audioRole:'narration',groupId:'b',narrationSegmentIds:['b']}),c('birds',5,10,{type:'audio',audioRole:'sound',allowOverlap:true})];
const caps=[{id:'b',start:4,end:7,text:'B',words:[{text:'B',start:4,end:5}]}];
const before=JSON.stringify({rows,caps});
const moved=moveTimelineClip(rows,caps,'first',2,true,true,.5);
assert.deepEqual(moved.clips.map(c=>c.start),[2,6.5,10,6.5,5]);
assert.equal(moved.segments[0].start,6.5);assert.equal(moved.segments[0].words[0].start,6.5);
assert.equal(JSON.stringify({rows,caps}),before);
assert.deepEqual(moveTimelineClip(rows,caps,'first',2,true,true,.5),moved,'stable repeated pointer update');
const back=moveTimelineClip(rows,caps,'second',-10,true,true,.5);assert(back.clips[1].start>=4.5);
const free=moveTimelineClip(rows,caps,'first',2,false,false);assert.equal(free.clips[1].start,4);
const enabled=separateSceneOverlaps(free.clips,free.segments,.5);assert.equal(enabled.clips[1].start,6.5);assert.equal(enabled.clips[4].start,5);
const voices=[c('v1',0,10,{type:'audio',audioRole:'narration',allowOverlap:true}),c('v2',2,4,{type:'audio',audioRole:'narration'}),c('v3',3,4,{type:'audio',audioRole:'narration'})];
assert.deepEqual(separateSceneOverlaps(voices,[]).clips.map(c=>c.start),[0,2,6]);
const fx=[{id:'sun',kind:'sunlight',start:0,end:10,allowOverlap:true},{id:'flash',kind:'lightning',start:2,end:4},{id:'flash2',kind:'lightning',start:3,end:5},{id:'clock',kind:'clock',start:1,end:3}];
assert.deepEqual(repairOverlayOverlaps(fx).map(o=>o.start),[0,2,4,1]);
const edit=editOverlayTiming(fx,fx.map(o=>o.id==='flash'?{...o,start:3,end:5}:o),true,true);
assert.deepEqual(edit.map(o=>o.start),[0,3,5,1]);
assert.deepEqual(editOverlayTiming(fx,fx,true,true),fx,'no spontaneous retiming on property edits');
assert.equal(rippleOverlays(fx,0,2)[0].start,0);
assert.equal(JSON.parse(JSON.stringify(fx))[0].allowOverlap,true);
console.log('Train movement, detached clip, linked narration/words, gap, backward bounds, toggle-off/repair, overlap exemptions for voices/effects, overlay lanes, repeated drag and persistence passed.');
