import assert from 'node:assert/strict';
import {loadTestModule} from './test-ts-module.mjs';
const {snapTime,rippleMove,clipsFollowCaptions,captionsFollowClips,narrationParts,fitCaptionSpeech,mergeSpeechCaptions}=await loadTestModule('lib/local-timeline.ts','work/local-timeline-tests');
const segments=[{id:'a',start:0,end:2,text:'Prva scena',words:[{text:'Prva',start:0,end:1}]},{id:'b',start:3,end:5,text:'Druga scena'},{id:'c',start:5,end:8,text:'Treća duža scena'}];
const original=JSON.stringify(segments);
assert.deepEqual(snapTime(3.04,2,[3,5],.1),{start:3,guide:3});
assert.deepEqual(snapTime(3.04,2,[3,5],.1,false),{start:3.04,guide:null});
assert.equal(snapTime(2.96,2,[5],.1).start,3);
const moved=rippleMove(segments,'b',1);
assert.deepEqual(moved.map(s=>[s.start,s.end]),[[0,2],[2,4],[4,7]]);
const clip={id:'image',captionId:'b',start:3,inPoint:0,outPoint:2};
const linked=clipsFollowCaptions([clip],segments,moved);
assert.equal(linked[0].start,2);
assert.deepEqual(captionsFollowClips([clip],[{...clip,start:4}],segments).map(s=>s.start),[0,4,6]);
assert.deepEqual(captionsFollowClips([clip],[{...clip,outPoint:4}],segments).map(s=>[s.start,s.end]),[[0,2],[3,7],[7,10]]);
assert.equal(clipsFollowCaptions([clip],segments,[])[0].captionId,undefined);
const fitted=fitCaptionSpeech(segments,1,8);
assert.deepEqual(fitted.map(s=>[s.start,s.end]),[[1,3],[3,5],[5,8]]);
assert.equal(fitted[0].words[0].start,1);
const merged=mergeSpeechCaptions(segments,'a',{start:0,end:7});
assert.equal(merged.length,2);assert.equal(merged[0].end,4);assert.equal(merged[1].start,4);
assert.deepEqual(narrationParts('„Stani!” rekao je vuk. Crvenkapica je zastala.'),['„Stani!” rekao je vuk.','Crvenkapica je zastala.']);
assert.deepEqual(narrationParts('Prva linija\nDruga linija'),['Prva linija','Druga linija']);
assert.equal(JSON.stringify(segments),original);
const {drawStillScene}=await loadTestModule('lib/still-scenes.tsx','work/local-timeline-tests');
const stack=[],draws=[];
const ctx={canvas:{width:100,height:100},globalAlpha:1,x:0,y:0,save(){stack.push([this.globalAlpha,this.x,this.y]);},restore(){[this.globalAlpha,this.x,this.y]=stack.pop();},translate(x,y){this.x+=x;this.y+=y;},drawImage(){draws.push([this.globalAlpha,this.x,this.y]);}};
const still={assetId:'image',start:0,inPoint:0,outPoint:5,layer:1,imageExitDuration:1};
const images=new Map([['image',{naturalWidth:100,naturalHeight:100}]]);
drawStillScene(ctx,images,{...still,imageExit:'fade'},4.5,1);
assert.deepEqual(draws.pop(),[.5,0,0]);assert.equal(ctx.globalAlpha,1);
drawStillScene(ctx,images,{...still,imageExit:'slide-left'},4.5,1);
assert.deepEqual(draws.pop(),[1,-50,0]);assert.equal(ctx.x,0);
console.log('Local magnets, ripple, linked clips, narration timing/quotes and shared exit rendering passed.');
