import assert from 'node:assert/strict';
import {loadTestModule} from './test-ts-module.mjs';
const {galleryScene,galleryFrameGroups}=await loadTestModule('lib/gallery-order.ts','work/gallery-tests');
const script={segments:[{id:'a',text:'Kerim provodi petak u svojoj sobi za racunarom.'},{id:'b',text:'Maja ustaje rano i otvara prozor sobe.'}],photo_settings:{}};
const asset=metadata=>({metadata});
assert.equal(galleryScene(asset({segmentId:'b'}),script),1);
assert.equal(galleryScene(asset({segmentId:'stale',fullPrompt:'Narration context: Kerim provodi petak u svojoj sobi za kompjuterom. Maja ustaje rano i otvara prozor sobe.\nScene direction: room'}),script),0);
assert.equal(galleryScene(asset({fullPrompt:'Narration context: Maja ustaje rano i otvara prozor sobe.\nScene direction: room'}),script),1);
assert.equal(galleryScene(asset({prompt:'Unrelated scene prompt long enough'}),script),-1);
assert.equal(galleryScene(asset({fullPrompt:'Narration context: Maja ustaje rano i otvara prozor sobe.\nScene direction: room'}),{...script,segments:[script.segments[1],script.segments[0],{...script.segments[1],id:'c'}]}),-1);
console.log('Gallery recovery: IDs, changed wording, contiguous context, ambiguity and unknown frames passed.');

const cachedAsset=asset({segmentId:'b'});
assert.equal(galleryScene(cachedAsset,script),1);
assert.equal(galleryScene(cachedAsset,script),1);
assert.equal(galleryScene(cachedAsset,{...script,segments:[...script.segments].reverse()}),0);
assert.equal(galleryScene({...cachedAsset,metadata:{segmentId:'a'}},script),0);
const promptAsset=asset({prompt:'A sufficiently detailed bedroom scene prompt'});
assert.equal(galleryScene(promptAsset,script),-1);
assert.equal(galleryScene(promptAsset,{...script,photo_settings:{prompts:{b:[{text:promptAsset.metadata.prompt}]}}}),1);
console.log('Gallery memo invalidates for changed scene order, metadata and prompt settings.');

assert.equal(galleryScene(asset({manualFrames:true,segmentIds:[],fullPrompt:'Narration context: Maja ustaje rano i otvara prozor sobe.'}),script),-1);
const frames=[{id:'a'},{id:'b'},{id:'c'},{id:'d'}];
assert.deepEqual(galleryFrameGroups(['b','a'],frames),[['a','b']]);
assert.deepEqual(galleryFrameGroups(['d','a','b'],frames),[['a','b'],['d']]);
assert.deepEqual(galleryFrameGroups([],frames),[]);
console.log('Manual unassignment and consecutive/non-consecutive image groups passed.');

const {photoCollections}=await loadTestModule('lib/gallery-order.ts','work/gallery-tests');
const photo=(id,gallery)=>({id,contentType:'image/png',metadata:{scriptId:'story',segmentId:'same-frame',gallery}});
let photos=[photo('one',false),photo('two',false),photo('three',true)];
assert.equal(photoCollections(photos,'story').pending.length,2);
photos=photos.map(a=>({...a,metadata:{...a.metadata,gallery:true}}));
assert.deepEqual(photoCollections(photos,'story').pictures.map(a=>a.id),['one','two','three']);
assert.equal(photoCollections(photos,'story').pending.length,0);
photos=photos.map(a=>a.id==='two'?{...a,metadata:{...a.metadata,gallery:false}}:a);
assert.deepEqual(photoCollections(photos,'story').pending.map(a=>a.id),['two']);
assert.deepEqual(photoCollections(photos,'story').pictures.map(a=>a.id),['one','three']);
console.log('Gallery live membership: all same-frame versions retained, moves are exclusive in both directions.');
