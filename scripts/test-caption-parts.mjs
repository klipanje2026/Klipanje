import assert from 'node:assert/strict';
import {loadTestModule} from './test-ts-module.mjs';
const out='work/caption-parts-tests';
const {splitVisualPart,expandVisualParts,patchVisualPart}=await loadTestModule('lib/caption-parts.ts',out);
const {toggleFrameLink}=await loadTestModule('lib/frame-links.ts',out);
const {clipsFollowCaptions}=await loadTestModule('lib/local-timeline.ts',out);
const {fitNarration}=await loadTestModule('lib/narration-sync.ts',out);
const {splitCaptionAt,mergeCaptionWithNext}=await loadTestModule('lib/caption-timing.ts',out);
const {patchLocalCaptionStyle}=await loadTestModule('lib/local-caption-style.ts',out);
const original={id:'scene',start:0,end:4,text:'Zeko zdravo Medo idemo',words:['Zeko','zdravo','Medo','idemo'].map((text,i)=>({text,start:i,end:i+1}))};
let s=splitVisualPart(original,2);s=splitVisualPart(s,3);
assert.equal(s.start,0);assert.equal(s.end,4);assert.equal(s.id,original.id);assert.deepEqual(s.words,original.words);
assert.equal(s.visualParts.length,3);assert.equal(original.visualParts,undefined);
const view=expandVisualParts(s);assert.deepEqual(view.map(p=>p.text),['Zeko zdravo','Medo','idemo']);assert.equal(view[1].words[0].start,2);
const moved=patchVisualPart(s,view[1].renderPartId,{x:75,y:60,fontScale:100},'clean');
assert.deepEqual(moved.visualParts[1].position,{x:75,y:60});assert.deepEqual(moved.visualParts[0].position,{x:25,y:75});
const doc={segments:[moved],activeStyle:'clean',captionSettings:{x:50,y:75,fontScale:100}};
const styled=patchLocalCaptionStyle(doc,'part:'+view[1].renderPartId,{textColor:'#abcdef'});
assert.equal(styled.segments.length,1);assert.equal(styled.segments[0].visualParts[1].detachedStyle.settings.textColor,'#abcdef');
assert.equal(styled.segments[0].visualParts[0].detachedStyle,undefined);
const image={id:'image',captionId:'scene',start:0,inPoint:0,outPoint:4};
assert.deepEqual(clipsFollowCaptions([image],[original],[moved]),[image]);
const split=splitCaptionAt([s],'scene',2);assert.equal(clipsFollowCaptions([image],[s],split)[0].outPoint,4);
const merged=mergeCaptionWithNext(split,'scene');assert.equal(expandVisualParts(merged[0]).map(p=>p.text).join(' '),original.text);
let groups=[['a','b'],['c','d']];groups=toggleFrameLink(['a','b','c','d','e'],groups,1);assert.deepEqual(groups,[['a','b','c','d']]);
groups=toggleFrameLink(['a','b','c','d','e'],groups,3);assert.deepEqual(groups,[['a','b','c','d','e']]);
groups=toggleFrameLink(['a','b','c','d','e'],groups,1);assert.deepEqual(groups,[['a','b'],['c','d','e']]);
const before=[{id:'a',start:0,end:3.5,text:'Zdravo medo'},{id:'b',start:3.5,end:7,text:'Zdravo zeko'}];
const first=fitNarration(before,{segmentIds:['a'],text:'Zdravo medo',words:[],duration:2,sync:true,placement:'scene'},0);
const second=fitNarration(first,{segmentIds:['b'],text:'Zdravo zeko',words:[],duration:2,sync:true,placement:'scene'},2);
const groupImage=clipsFollowCaptions([{id:'both',segmentIds:['a','b'],start:0,inPoint:0,outPoint:7}],before,second)[0];
assert.equal(groupImage.outPoint,4);assert.equal(groupImage.start,0);
console.log('Visual caption parts preserve one timeline block, word times, linked images and separate styling; adjacent groups extend and split; one image spans both narrations.');
const {activeCaptionSegments}=await loadTestModule('lib/caption-selection.ts',out);
const rendered=activeCaptionSegments([moved],2,'clean',{x:50,y:75,fontScale:100});
assert.equal(rendered.length,3);assert.deepEqual(rendered.map(p=>p.text),['Zeko zdravo','Medo','idemo']);
assert.deepEqual(rendered[1].position,{x:75,y:60});
assert.equal(activeCaptionSegments([moved],4,'clean',{x:50,y:75,fontScale:100}).length,0);
const changedSplit=split.map((p,i)=>i===1?{...p,end:5}:p);
assert.equal(clipsFollowCaptions([image],split,changedSplit)[0].outPoint,5);
const {toggleVisualPartAtCursor,visualBoundaryAtCursor}=await loadTestModule('lib/caption-parts.ts',out);
const letters={id:'letters',start:2,end:4,text:'Medo',words:[{text:'Medo',start:2,end:4}]};
let separated=letters;
for(let cursor=1;cursor<4;cursor++)separated=toggleVisualPartAtCursor(separated,cursor);
assert.deepEqual(expandVisualParts(separated).map(p=>p.text),['M','e','d','o']);
assert.deepEqual(expandVisualParts(separated).map(p=>[p.words[0].start,p.words[0].end]),[[2,2.5],[2.5,3],[3,3.5],[3.5,4]]);
separated=toggleVisualPartAtCursor(separated,2);
assert.deepEqual(expandVisualParts(separated).map(p=>p.text),['M','ed','o']);
for(const cursor of [1,3])separated=toggleVisualPartAtCursor(separated,cursor);
assert.equal(separated.visualParts,undefined);assert.equal(separated.text,letters.text);assert.deepEqual(separated.words,letters.words);
assert.equal(visualBoundaryAtCursor('Jedan dva tri četiri',13),3);
assert.equal(visualBoundaryAtCursor('Jedan dva tri četiri',14),3);
const once=toggleVisualPartAtCursor(original,11),twice=toggleVisualPartAtCursor(once,11);
assert.equal(twice.visualParts,undefined);assert.deepEqual(twice.words,original.words);
assert.equal(visualBoundaryAtCursor('A😀B',2),.75);
console.log('Cursor boundaries toggle repeatedly, including each letter; word timings and timeline remain unchanged.');
