import assert from 'node:assert/strict';
import {loadTestModule} from './test-ts-module.mjs';
const {moveSceneRipple,separateSceneOverlaps,rippleTimingEdit}=await loadTestModule('lib/scene-ripple.ts','work/ripple-tests');
const {clipsFollowCaptions}=await loadTestModule('lib/local-timeline.ts','work/ripple-tests');
const clip=(id,start,length,extra={})=>({id,type:'video',layer:1,start,inPoint:0,outPoint:length,segmentIds:[id],...extra});
const clips=[clip('a',0,2),clip('b',3,3),clip('c',7,2),clip('voice',3,3,{type:'audio',layer:2,segmentIds:undefined,narrationSegmentIds:['b']}),clip('music',0,30,{type:'audio',layer:3,segmentIds:undefined}),clip('overlay',0,12,{layer:4,segmentIds:undefined})];
const segments=clips.slice(0,3).map(c=>({id:c.id,text:c.id,start:c.start,end:c.start+c.outPoint,words:[{text:c.id,start:c.start,end:c.start+1}]}));
const before=JSON.stringify({clips,segments});
const move=moveSceneRipple(clips,segments,'b',8);
assert.deepEqual(move.clips.map(c=>c.start),[0,8,12,8,0,0]);assert.deepEqual(move.segments.map(s=>s.start),[0,8,12]);assert.equal(move.segments[1].words[0].start,8);
assert.equal(moveSceneRipple(clips,segments,'b',-10).clips[1].start,2);
const overlapping=[clip('a',0,4),clip('b',2,3),clip('c',3,2)];const repaired=separateSceneOverlaps(overlapping,segments);assert.deepEqual(repaired.clips.map(c=>c.start),[0,4,7]);
assert.deepEqual(separateSceneOverlaps(repaired.clips,repaired.segments),repaired,'repair is idempotent');
assert.equal(JSON.stringify({clips,segments}),before,'undo snapshot is not mutated');
const manual=clip('manual',10,5,{segmentIds:['a']});assert.equal(clipsFollowCaptions([manual],segments,segments)[0],manual,'unrelated edits must not reset manual image placement');
console.log('Scene ripple: gaps, collisions, linked voice/words, layer isolation, repair and stable manual placement passed.');

const resized=clips.map(c=>c.id==='a'?{...c,outPoint:5}:c);
const resizedResult=rippleTimingEdit(clips,resized,segments,segments,true,true);
assert.equal(resizedResult.clips.find(c=>c.id==='b').start,6);
assert.equal(resizedResult.clips.find(c=>c.id==='voice').start,6);
assert.equal(resizedResult.clips.find(c=>c.id==='music').start,0);
assert.equal(resizedResult.segments[1].start,6);
const captionEdit=segments.map(s=>s.id==='a'?{...s,end:5}:s);
const captionResult=rippleTimingEdit(clips,clips,segments,captionEdit,true,false);
assert.equal(captionResult.clips.find(c=>c.id==='b').start,6);
const alreadyMoved=resized.map(c=>c.id==='b'||c.id==='voice'?{...c,start:6}:c);
assert.equal(rippleTimingEdit(clips,alreadyMoved,segments,captionEdit,true,true).clips.find(c=>c.id==='b').start,6,'linked items move once');
assert.equal(rippleTimingEdit(clips,resized,segments,segments,false,true).clips.find(c=>c.id==='b').start,5,'no overlap still works when ripple is off');
console.log('Resize and caption edits ripple following media once; no-overlap works independently.');

assert.equal(rippleTimingEdit(overlapping,overlapping,segments,segments,true,true).clips,overlapping,'non-timing edits never repair saved layout implicitly');
const {closeFollowingGap}=await loadTestModule('lib/close-following-gap.ts','work/ripple-tests');
const gapClips=[clip('first',0,2,{groupId:'first'}),clip('third',8,3,{groupId:'third'}),clip('voice3',8,3,{type:'audio',audioRole:'narration',groupId:'third',segmentIds:undefined,narrationSegmentIds:['third']}),clip('fourth',14,2),clip('sound',15,1,{type:'audio',audioRole:'sound',segmentIds:undefined}),clip('bg',0,30,{type:'audio',audioRole:'music',segmentIds:undefined})];
const gapCaptions=[{id:'first',text:'First',start:0,end:2},{id:'third',text:'Third',start:8,end:11,words:[{text:'Third',start:8,end:9}]},{id:'fourth',text:'Fourth',start:14,end:16}];
const decorations=[{start:15,end:17},{start:0,end:30}];
const untouched=JSON.stringify({gapClips,gapCaptions,decorations});
const closed=closeFollowingGap(gapClips,gapCaptions,decorations,{clipId:'first'});
assert.equal(closed.gap,6);assert.deepEqual(closed.clips.map(c=>c.start),[0,2,2,8,9,0]);
assert.deepEqual(closed.segments.map(s=>s.start),[0,2,8]);assert.equal(closed.segments[1].words[0].start,2);
assert.deepEqual(closed.overlays,[{start:9,end:11},{start:0,end:30}]);
assert.equal(JSON.stringify({gapClips,gapCaptions,decorations}),untouched);
assert.equal(closeFollowingGap(closed.clips,closed.segments,closed.overlays,{clipId:'first'}).gap,0);
assert.equal(closeFollowingGap(gapClips,gapCaptions,decorations,{captionId:'first'}).gap,6);
assert.equal(closeFollowingGap(gapClips,gapCaptions,decorations,{clipId:'fourth'}).gap,0);
assert.equal(closeFollowingGap(gapClips,gapCaptions,decorations,{}).gap,0);
const earlyVoice=gapClips.map(c=>c.id==='voice3'?{...c,start:7}:c);
const early=closeFollowingGap(earlyVoice,gapCaptions,decorations,{clipId:'first'});
assert.equal(early.gap,5);assert.equal(early.clips[1].start-early.clips[2].start,1);
console.log('Close following gap: linked tail, captions/words, sounds/overlays, preserved gaps/durations, untouched background, repeat/no-op and source immutability passed.');
