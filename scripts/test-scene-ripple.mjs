assert.ok(onlyIndependentAudioChanged(scene,clips));
assert.ok(onlyIndependentAudioChanged(clips,scene));
assert.ok(!onlyIndependentAudioChanged(scene,scene.map(c=>c.id==='a'?{...c,outPoint:9}:c)));
assert.ok(!onlyIndependentAudioChanged(scene,scene));
console.log('Independent sound/music edits bypass caption sync, ripple and overlap repair; narration and image edits retain normal behavior.');
