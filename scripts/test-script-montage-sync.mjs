import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
import {loadTestModule} from './test-ts-module.mjs';
const {syncScriptDocument,scriptSourceKey,scriptChoices}=await loadTestModule('lib/script-montage-sync.ts','work/sync-tests');
const {swapSceneBundles}=await loadTestModule('lib/scene-swap.ts','work/sync-tests');
const {rippleMove}=await loadTestModule('lib/local-timeline.ts','work/sync-tests');
const {resizeCaptionRipple}=await loadTestModule('lib/caption-timing.ts','work/sync-tests');
const segment=(id,start,end,text=id)=>({id,start,end,text,words:[{text,start,end}]});
const old=[segment('a',0,2),segment('b',2,5)];
const script={segments:old,photo_settings:{},storyboard:{savedAt:'2026-10-20'}};
const clip={id:'image',assetId:'image',type:'video',captionId:'a',start:0,inPoint:0,outPoint:2,layer:1};
const data={clips:[clip],captions:{__script:{segments:[...old, {...segment('title',0,1),role:'title'}],captionSettings:{fontSize:44}}},scriptSync:{sourceKey:scriptSourceKey(script),choices:{}}};
const next=syncScriptDocument(data,{...script,segments:[segment('a',0,4,'New text'),segment('b',4,7)]});
assert.equal(next.clips[0].outPoint,4);
assert.equal(next.captions.__script.segments[0].text,'New text');
assert.equal(next.captions.__script.segments[1].start,4);
assert.equal(next.captions.__script.segments.at(-1).role,'title');
assert.equal(next.captions.__script.captionSettings.fontSize,44);
const deleted={...data,clips:[],captions:{__script:{segments:[]}}};
assert.equal(syncScriptDocument(deleted,script),deleted,'unchanged source must not restore deleted captions or media');
const audio={...clip,id:'voice',type:'audio',audioRole:'narration',captionId:undefined,narrationSegmentIds:['a']};
const other={...clip,id:'other',captionId:'b',start:2,outPoint:3};
const bg={...audio,id:'bg',narrationSegmentIds:undefined,start:0,outPoint:10};
const swap=swapSceneBundles([clip,audio,other,bg],old,'image','other');
assert.deepEqual(swap.clips.map(c=>c.start),[3,3,0,0]);
assert.deepEqual(swap.segments.map(s=>[s.start,s.end]),[[3,5],[0,3]]);
assert.deepEqual(old.map(s=>s.start),[0,2],'swap cannot mutate undo snapshot');
const detached=[{...old[0],independentTiming:true},old[1]];
assert.equal(rippleMove(detached,'a',1)[1].start,2);
assert.equal(resizeCaptionRipple(detached,'a',1,10)[1].start,2);

