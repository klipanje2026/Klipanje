import assert from 'node:assert/strict';
import {loadTestModule} from './test-ts-module.mjs';
const {separateSceneOverlaps,freeClipStart}=await loadTestModule('lib/scene-ripple.ts','work/overlap-repair-tests');
const {detachAllStoryLinks}=await loadTestModule('lib/story-links.ts','work/overlap-repair-tests');
const c=(id,start,len,props={})=>({id,type:'audio',audioRole:'sound',layer:1,start,inPoint:0,outPoint:len,...props});
const sounds=[c('waves',0,20,{allowOverlap:true}),c('birds',2,4),c('third',3,5)];
const repaired=separateSceneOverlaps(sounds,[]);
assert.deepEqual(repaired.clips.map(c=>c.start),[0,2,6]);
assert.equal(freeClipStart(sounds,'birds',10),10,'one exempt clip is enough for bilateral overlap');
assert.equal(freeClipStart(sounds,'waves',3),3);
const linked=[c('imgA',0,10,{type:'video',groupId:'a',segmentIds:['a']}),c('imgB',5,10,{type:'video',groupId:'b',segmentIds:['b']}),c('voiceA',0,20,{audioRole:'narration',groupId:'a',narrationSegmentIds:['a']}),c('voiceB',10,5,{audioRole:'narration',groupId:'b',narrationSegmentIds:['b']})];
const segments=[{id:'a',start:0,end:20,text:'A'},{id:'b',start:10,end:15,text:'B'}];
const result=separateSceneOverlaps(linked,segments);
assert.deepEqual(result.clips.map(c=>c.start),[0,15,0,20]);
assert.equal(result.segments[1].start,20,'subtitle follows repaired narration');
assert.deepEqual(separateSceneOverlaps(result.clips,result.segments),result,'repeat does not create fresh overlaps');
const detached=detachAllStoryLinks(linked);
assert.deepEqual(detached.map(c=>[c.start,c.inPoint,c.outPoint]),linked.map(c=>[c.start,c.inPoint,c.outPoint]));
assert(detached.every(c=>c.linksDetached&&!c.groupId&&!c.segmentIds&&!c.narrationSegmentIds));
const pictures=[c('a',0,5,{type:'video',linksDetached:true}),c('b',10,5,{type:'video'})];
assert.equal(freeClipStart(pictures,'a',7),5,'detached picture stops at neighbour');
assert.equal(pictures[1].start,10);
assert.equal(JSON.parse(JSON.stringify(repaired.clips))[0].allowOverlap,true);
console.log('Repair regression passed: bilateral exemption, ordinary collisions, linked lanes, subtitle timing, idempotence, detach all preserves timing, isolated move and persisted flag.');
